"""Pre-configure Wi-Fi networks on an Onion SD card.

Upstream writes a one-shot ``.tmp_update/runtime.sh`` that appends a wpa_supplicant network
block to ``/appconfigs/wpa_supplicant.conf`` on the console, then restores and runs the
original ``runtime.sh`` (saved as ``runtime_ori.sh``).

Security change versus upstream: credentials are **never interpolated into shell code**.
They are written, validated and encoded in wpa_supplicant syntax, to a data file that a
static script appends with ``cat``. This removes the command-injection path on the device.
"""

from __future__ import annotations

import os
import string
from pathlib import Path

from ..core.exceptions import OdtError, ValidationError
from ..core.safe_fs import fsync_dir, open_new_file

RUNTIME = Path(".tmp_update/runtime.sh")
RUNTIME_ORI = Path(".tmp_update/runtime_ori.sh")
PENDING_FILE = Path(".tmp_update/odt_wifi_networks.conf")
_HEX = set(string.hexdigits)

HOOK_SCRIPT = """#!/bin/sh
# One-shot hook generated by Onion Desktop Tools (Linux).
# Appends pending Wi-Fi networks to wpa_supplicant.conf, then restores the original runtime.sh.
killall -9 main
killall -9 updater
if [ ! -f /appconfigs/wpa_supplicant.conf ]; then
    echo "ctrl_interface=/var/run/wpa_supplicant" > /appconfigs/wpa_supplicant.conf
    echo "update_config=1" >> /appconfigs/wpa_supplicant.conf
fi
if [ -f /mnt/SDCARD/.tmp_update/odt_wifi_networks.conf ]; then
    cat /mnt/SDCARD/.tmp_update/odt_wifi_networks.conf >> /appconfigs/wpa_supplicant.conf
    rm -f /mnt/SDCARD/.tmp_update/odt_wifi_networks.conf
    sync
fi
mv "/mnt/SDCARD/.tmp_update/runtime_ori.sh" "/mnt/SDCARD/.tmp_update/runtime.sh"
/mnt/SDCARD/.tmp_update/runtime.sh
"""


def validate_ssid(ssid: str) -> bytes:
    raw = ssid.encode("utf-8")
    if not 1 <= len(raw) <= 32:
        raise ValidationError("The network name (SSID) must be 1 to 32 bytes long.")
    if any(c in ssid for c in "\x00\r\n"):
        raise ValidationError("The network name contains invalid control characters.")
    return raw


def validate_password(password: str) -> str:
    """Empty = open network; 8–63 printable ASCII = WPA passphrase; 64 hex = raw PSK."""
    if password == "":
        return password
    if len(password) == 64 and all(c in _HEX for c in password):
        return password
    if not 8 <= len(password) <= 63:
        raise ValidationError("A WPA password must be 8 to 63 characters (or 64 hex digits).")
    if any(not (0x20 <= ord(c) <= 0x7E) for c in password):
        raise ValidationError("A WPA password may only contain printable ASCII characters.")
    return password


def _needs_hex(raw: bytes) -> bool:
    try:
        text = raw.decode("ascii")
    except UnicodeDecodeError:
        return True
    return any(not (0x20 <= ord(c) <= 0x7E) or c in '"\\' for c in text)


def network_block(ssid: str, password: str) -> str:
    raw = validate_ssid(ssid)
    password = validate_password(password)
    ssid_line = f"ssid={raw.hex()}" if _needs_hex(raw) else f'ssid="{raw.decode("ascii")}"'
    lines = ["", "network={", f"        {ssid_line}"]
    if password == "":
        lines.append("        key_mgmt=NONE")
    elif len(password) == 64 and all(c in _HEX for c in password):
        lines.append(f"        psk={password.lower()}")
    else:
        # wpa_supplicant parses a quoted value up to the *last* quote, so inner quotes are safe;
        # the value cannot contain newlines (validated above).
        lines.append(f'        psk="{password}"')
    lines.append("}")
    return "\n".join(lines) + "\n"


def has_pending(card_root: Path) -> bool:
    return (card_root / RUNTIME_ORI).is_file()


def pending_ssid_count(card_root: Path) -> int:
    try:
        return (card_root / PENDING_FILE).read_text(encoding="utf-8").count("network={")
    except OSError:
        return 0


def _write(path: Path, text: str, mode: int = 0o644) -> None:
    tmp = path.with_name(".odt-tmp-" + path.name)
    data = text.encode("utf-8")
    fd = open_new_file(tmp, mode)
    try:
        os.write(fd, data)
        os.fsync(fd)
    finally:
        os.close(fd)
    os.replace(tmp, path)


def add_network(card_root: Path, ssid: str, password: str) -> None:
    """Queue *ssid* to be added to the console's Wi-Fi configuration on its next boot."""
    block = network_block(ssid, password)
    runtime = card_root / RUNTIME
    runtime_ori = card_root / RUNTIME_ORI
    for p in (runtime, runtime_ori, card_root / PENDING_FILE):
        if p.is_symlink():
            raise OdtError(f"Refusing to modify symbolic link {p.name}.")
    if not runtime_ori.is_file():
        if not runtime.is_file():
            raise OdtError(
                "Onion OS is not installed on this card (.tmp_update/runtime.sh is missing).",
                hint="Install Onion and boot it once on the console before configuring Wi-Fi.",
            )
        os.replace(runtime, runtime_ori)
    pending = card_root / PENDING_FILE
    existing = pending.read_text(encoding="utf-8") if pending.is_file() else ""
    _write(pending, existing + block, 0o600)
    _write(runtime, HOOK_SCRIPT, 0o755)
    fsync_dir(card_root / ".tmp_update")


def cancel_pending(card_root: Path) -> bool:
    """Undo queued Wi-Fi changes; returns True if something was undone."""
    runtime_ori = card_root / RUNTIME_ORI
    if not runtime_ori.is_file():
        return False
    os.replace(runtime_ori, card_root / RUNTIME)
    (card_root / PENDING_FILE).unlink(missing_ok=True)
    fsync_dir(card_root / ".tmp_update")
    return True
